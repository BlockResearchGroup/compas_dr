from compas_dr.numdata import InputData
from compas_dr.solvers import dr_numpy

# ==============================================================================
# Parameters
# ==============================================================================

vertices = [[1, 0, 0], [0, 0, 0], [4, 0, 0]]
edges = [(0, 1), (0, 2)]
fixed = [1, 2]
loads = [[0, 0, -4], [0, 0, 0], [0, 0, 0]]
qpre = [1, 3]

# ==============================================================================
# Solve
# ==============================================================================

data = InputData(
    vertices=vertices,
    edges=edges,
    fixed=fixed,
    loads=loads,
    qpre=qpre,
)
result = dr_numpy(data)

# ==============================================================================
# Result
# ==============================================================================

print("Free vertex at", result.xyz[0])
